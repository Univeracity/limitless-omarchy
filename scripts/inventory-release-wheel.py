#!/usr/bin/env python3
"""Map every member of an existing release wheel to source or checked generation."""

from __future__ import annotations

import argparse
import base64
import csv
import hashlib
import importlib.metadata
import io
import json
import os
import re
import shutil
import stat

# Fixed argv and a pinned public source archive; no shell or agent-supplied command.
import subprocess  # nosec B404
import sys
import tarfile
import tempfile
import tomllib
import zipfile
from pathlib import Path, PurePosixPath


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def git(root: Path, *arguments: str) -> bytes:
    executable = shutil.which("git")
    if executable is None:
        raise ValueError("Git is required to read the pinned source archive")
    # Call sites provide fixed archive/rev-parse operations and a validated SHA.
    return subprocess.check_output([executable, "-C", str(root), *arguments])  # nosec B603


def verify_contents(
    wheel: Path, source: dict[str, bytes], metadata: dict[str, bytes], *, backend_version: str
) -> list[dict[str, object]]:
    """Require a closed file set, source/generated bytes and complete RECORD."""
    package = "limitless_omarchy/"
    configuration = tomllib.loads(source["pyproject.toml"].decode())
    project = configuration["project"]
    info = f"limitless_omarchy-{project['version']}.dist-info/"
    expected = {name.removeprefix("src/"): data for name, data in source.items() if name.startswith("src/" + package)}
    origins = {name: {"kind": "exact-source", "paths": ["src/" + name]} for name in expected}
    for name in project["license-files"]:
        path = info + "licenses/" + name
        expected[path] = source[name]
        origins[path] = {"kind": "exact-source", "paths": [name]}
    for name in ("METADATA", "entry_points.txt", "top_level.txt"):
        path = info + name
        expected[path] = metadata[name]
        origins[path] = {
            "kind": "exact-regenerated-metadata",
            "backend": "setuptools.build_meta",
            "paths": ["pyproject.toml", project["readme"], *project["license-files"], "src/limitless_omarchy/"],
        }
    expected[info + "WHEEL"] = (
        f"Wheel-Version: 1.0\nGenerator: setuptools ({backend_version})\nRoot-Is-Purelib: true\nTag: py3-none-any\n\n"
    ).encode()
    origins[info + "WHEEL"] = {
        "kind": "checked-backend-format",
        "paths": ["pyproject.toml", "src/limitless_omarchy/"],
        "explanation": "Wheel format 1.0, declared setuptools generator, pure-Python installation and py3-none-any tag.",
    }
    record_path = info + "RECORD"
    origins[record_path] = {
        "kind": "complete-archive-record",
        "explanation": "Every archive member exactly once, with SHA256 and size; only RECORD itself has empty hash and size.",
    }
    inventory = []
    with zipfile.ZipFile(wheel) as archive:
        names = archive.namelist()
        if len(names) != len(set(names)):
            raise ValueError("wheel contains duplicate member paths")
        for member in archive.infolist():
            logical = PurePosixPath(member.filename)
            mode = member.external_attr >> 16
            if (
                logical.is_absolute()
                or logical.as_posix() != member.filename
                or ".." in logical.parts
                or "\\" in member.filename
                or member.is_dir()
                or stat.S_ISLNK(mode)
            ):
                raise ValueError("wheel contains an unsafe member")
        if set(names) != set(expected) | {record_path}:
            raise ValueError("complete wheel file set differs from source and expected metadata")
        delivered = {name: archive.read(name) for name in names}
        for name, data in expected.items():
            if delivered[name] != data:
                raise ValueError(f"wheel file differs from its source or checked generation: {name}")
        rows = list(csv.reader(io.StringIO(delivered[record_path].decode("utf-8"))))
        if any(len(row) != 3 for row in rows) or len(rows) != len(names) or {row[0] for row in rows} != set(names):
            raise ValueError("RECORD is not a complete, unique inventory")
        for name, claimed_hash, size in rows:
            if name == record_path:
                if claimed_hash or size:
                    raise ValueError("RECORD self-entry must have empty hash and size")
            else:
                data = delivered[name]
                encoded = base64.urlsafe_b64encode(hashlib.sha256(data).digest()).decode().rstrip("=")
                if claimed_hash != "sha256=" + encoded or size != str(len(data)):
                    raise ValueError(f"RECORD does not bind the delivered bytes: {name}")
        for name in sorted(names):
            inventory.append(
                {
                    "path": name,
                    "bytes": len(delivered[name]),
                    "sha256": digest(delivered[name]),
                    "unixMode": f"{archive.getinfo(name).external_attr >> 16:06o}",
                    "installationScheme": "purelib",
                    "sourceMapping": origins[name],
                }
            )
    return inventory


def inventory(source_root: Path, recipe_path: Path, wheel: Path, output: Path) -> dict[str, object]:
    recipe = json.loads(recipe_path.read_text())
    if recipe["schemaVersion"] != "limitless.adapter-wheel-inventory-recipe/1":
        raise ValueError("unsupported inventory recipe")
    commit = recipe["source"]["commit"]
    if not isinstance(commit, str) or not re.fullmatch(r"[0-9a-f]{40}", commit):
        raise ValueError("historical source must be a full commit SHA")
    backend_version = recipe["metadataBackend"]["version"]
    if importlib.metadata.version("setuptools") != backend_version:
        raise ValueError("setuptools does not match the metadata-generation recipe")
    if wheel.name != recipe["wheel"]["name"] or digest(wheel.read_bytes()) != recipe["wheel"]["sha256"]:
        raise ValueError("wheel does not match the exact released digest and name")
    data = git(source_root, "archive", commit)
    with tarfile.open(fileobj=io.BytesIO(data)) as archive:
        source = {member.name: archive.extractfile(member).read() for member in archive.getmembers() if member.isfile()}
    if wheel.read_bytes() != source[recipe["wheel"]["bundledPath"]]:
        raise ValueError("release download differs from the wheel in the historical source tree")
    configuration = tomllib.loads(source["pyproject.toml"].decode())
    if configuration["build-system"] != {
        "requires": [f"setuptools=={backend_version}"],
        "build-backend": "setuptools.build_meta",
    }:
        raise ValueError("historical build backend does not match the declared recipe")
    output.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="adapter-metadata-") as temporary:
        clean = Path(temporary) / "source"
        clean.mkdir()
        with tarfile.open(fileobj=io.BytesIO(data)) as archive:
            archive.extractall(clean, filter="data")
        metadata_root = Path(temporary) / "metadata"
        metadata_root.mkdir()
        environment = {key: os.environ[key] for key in ("PATH", "HOME", "LANG", "TMPDIR") if key in os.environ}
        environment["PYTHONNOUSERSITE"] = "1"
        command = (
            "from setuptools.build_meta import prepare_metadata_for_build_wheel; "
            "import sys; prepare_metadata_for_build_wheel(sys.argv[1])"
        )
        # Fixed isolated interpreter and metadata hook over the pinned archive.
        subprocess.run(  # nosec B603
            [sys.executable, "-I", "-c", command, str(metadata_root)],
            cwd=clean,
            env=environment,
            capture_output=True,
            timeout=60,
            check=True,
        )
        folders = list(metadata_root.glob("*.dist-info"))
        if len(folders) != 1:
            raise ValueError("backend did not produce one metadata directory")
        metadata = {
            name: (folders[0] / name).read_bytes() for name in ("METADATA", "entry_points.txt", "top_level.txt")
        }
        files = verify_contents(wheel, source, metadata, backend_version=backend_version)
    inputs = [
        {"path": name, "sha256": digest(value)}
        for name, value in sorted(source.items())
        if name in {"pyproject.toml", "README.md", "LICENSE", "NOTICE"} or name.startswith("src/limitless_omarchy/")
    ]
    run = os.environ.get("GITHUB_RUN_ID")
    repository = os.environ.get("GITHUB_REPOSITORY")
    report = {
        "schemaVersion": "limitless.adapter-wheel-inventory/1",
        "source": {
            **recipe["source"],
            "tree": git(source_root, "rev-parse", f"{commit}^{{tree}}").decode().strip(),
            "archiveSha256": digest(data),
        },
        "wheel": recipe["wheel"],
        "metadataBackend": recipe["metadataBackend"],
        "sourceInputs": inputs,
        "files": files,
        "checks": {
            "completeArchiveInventory": True,
            "sourceBytesExact": True,
            "generatedMetadataBytesExact": True,
            "wheelDescriptorChecked": True,
            "completeRecordVerified": True,
            "releaseEqualsBundledWheel": True,
        },
        "scope": "Existing release contents/source correspondence; no wheel rebuild, original-build attestation, or security audit.",
        "builder": {
            "repository": repository,
            "commit": os.environ.get("GITHUB_SHA"),
            "runUrl": f"https://github.com/{repository}/actions/runs/{run}" if run and repository else None,
            "runAttempt": os.environ.get("GITHUB_RUN_ATTEMPT"),
        },
    }
    (output / "wheel-inventory.json").write_text(json.dumps(report, indent=2) + "\n")
    shutil.copyfile(wheel, output / wheel.name)
    return report


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-root", type=Path, required=True)
    parser.add_argument("--recipe", type=Path, required=True)
    parser.add_argument("--wheel", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    try:
        report = inventory(args.source_root, args.recipe, args.wheel, args.output)
    except (OSError, ValueError, KeyError, subprocess.SubprocessError, zipfile.BadZipFile) as error:
        print(f"wheel inventory failed: {error}", file=sys.stderr)
        return 1
    print(
        json.dumps(
            {
                "wheel": report["wheel"],
                "source": report["source"],
                "files": len(report["files"]),
                "checks": report["checks"],
            },
            indent=2,
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
